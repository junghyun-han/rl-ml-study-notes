import os, numpy as np, torch, torch.nn as nn, gymnasium as gym
import action_toolbox as T
ok = lambda n, c: print(("통과 " if c else "실패 ") + n)
env = T.make_env("Pendulum-v1", norm_obs=True, norm_reward=True, clip_action=True); env.reset(seed=0); env.action_space.seed(0)
for _ in range(500):
    o, r, te, tr, _ = env.step(env.action_space.sample())
    if te or tr: env.reset()
src = T.find_wrapper(env, gym.wrappers.NormalizeObservation)
ok(f"T1 정규화 켜짐: 관측 통계 {src.obs_rms.count:.0f}개 누적, 정규화된 관측 평균 크기 {abs(o).mean():.2f}", src.obs_rms.count > 400)
ev = T.make_eval_env("Pendulum-v1", env, clip_action=True); dst = T.find_wrapper(ev, gym.wrappers.NormalizeObservation)
before = dst.obs_rms.mean.copy()
m, s = T.evaluate_env(ev, lambda o: np.zeros(1, dtype=np.float32), episodes=3)
ok(f"T2 평가 환경: 학습 통계 복사·평가 중 고정, 보상 정규화 없음(원래 점수 {m:.1f})", np.allclose(before, src.obs_rms.mean) and np.allclose(dst.obs_rms.mean, before) and T.find_wrapper(ev, gym.wrappers.NormalizeReward) is None and m < -100)
net = nn.Linear(3, 1); opt = torch.optim.Adam(net.parameters(), lr=3e-4); T.set_lr(opt, 1e-4)
ok("T3 학습률 변경 3e-4 → 1e-4", opt.param_groups[0]["lr"] == 1e-4)
T.set_lr(opt, 1e-3); sch = T.linear_decay(opt, 10)
for _ in range(5): opt.step(); sch.step()
ok(f"T3 선형 감소: 10번 중 5번 뒤 학습률 {opt.param_groups[0]['lr']:.1e} (처음의 절반)", np.isclose(opt.param_groups[0]["lr"], 5e-4))
lp = torch.randn(64); ok(f"T4 근사 KL: 같은 정책 0, 다른 정책 {T.approx_kl(lp + 0.3*torch.randn(64), lp):.4f} ≥ 0", T.approx_kl(lp, lp) == 0 and T.approx_kl(lp + 0.3*torch.randn(64), lp) >= 0)
T.save_model(net, "results/_tmp.pt"); n2 = T.load_model(nn.Linear(3, 1), "results/_tmp.pt"); os.remove("results/_tmp.pt")
ok("T5 저장·불러오기 후 가중치 같음", torch.equal(net.weight, n2.weight))
sc = T.run_seeds("mock_ppo.py", ["--env", "CartPole-v1", "--steps", "4096", "--save", "results/_curve.txt"], [0, 1])
ok("T6 시드 2개 자동 실행·점수 수집", len(sc) == 2)
T.plot_curves({"seed1": np.loadtxt("results/_curve.txt")}, "results/_curve.png", w=10, title="CartPole PPO (4096 steps)")
ok("T7 곡선 그림 저장 + mock --save 기록", os.path.exists("results/_curve.png") and len(np.loadtxt("results/_curve.txt")) > 10)
os.remove("results/_curve.txt"); os.remove("results/_curve.png")
